// Real final offline HTML; disposable, offline, OS-muted browser. No user storage touched.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
const html=path.resolve('outputs/本地离线版/小红花应急行动.html');
const out=path.resolve(process.env.FIRST_AID_AUDIO_REPORT_DIR || 'outputs/first-aid-audio-verification');fs.mkdirSync(out,{recursive:true});
const report={status:'running',html,sha256:createHash('sha256').update(fs.readFileSync(html)).digest('hex'),checks:[],errors:[],network:[],realDevice:'not_run',humanAudio:'not_run',closed:false};
let browser,context,page;
const pass=text=>{report.checks.push(text);console.log('PASS '+text);};
try {
 browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE,args:['--mute-audio']});
 context=await browser.newContext({viewport:{width:390,height:844},offline:true,reducedMotion:'reduce'});
 await context.addInitScript(()=>{window.__testAudio=[];const Native=window.AudioContext;window.AudioContext=class extends Native{constructor(...args){super(...args);window.__testAudio.push(this);}};});
 page=await context.newPage();page.on('pageerror',error=>report.errors.push(error.message));page.on('request',r=>{if(/^https?:/.test(r.url()))report.network.push(r.url());});
 await page.goto(pathToFileURL(html).href,{waitUntil:'load',timeout:120000});
 await page.locator('[data-home-unlock-all]').click();await page.locator('[data-home-start]').click();await page.locator('[data-journey-map]').waitFor();
 await page.locator('[data-map-fan-toggle]').click();await page.locator('[data-island="first-aid"]').click();
 await page.waitForFunction(()=>Number(document.querySelector('.game-page')?.dataset.uiAudioPlayed)>0);
 pass('First-aid island inherits the same shared map/button sounds');
 const enter=async id=>{const node=page.locator(`[data-map-node="${id}"]`);await node.scrollIntoViewIfNeeded();await node.locator('.garden-node-label').click();await page.locator('[data-painted-primary]').click();};
 await enter('first-aid-cpr');await page.locator('[data-cpr-call]').waitFor();
 const root=page.locator('[data-cpr-player]');
 const cue=async name=>{await page.waitForFunction(name=>{const d=document.querySelector('[data-cpr-player]')?.dataset;return d?.audioCue===name&&Number(d.audioPlayed)>0;},name,{timeout:5000});};
 const played=async()=>Number(await root.getAttribute('data-audio-played'));
 const review=async()=>{await page.locator('[data-cpr-review]').waitFor();await page.waitForFunction(()=>document.querySelector('[data-cpr-player]')?.dataset.reviewMs==='0',null,{timeout:8000});await page.locator('[data-cpr-continue]').click();};
 await page.locator('[data-cpr-call]').click();await cue('medical-connect');await review();
 await page.locator('[data-cpr-aed]').click();await cue('medical-connect');await review();
 await page.waitForFunction(()=>document.querySelector('[data-cpr-player]')?.dataset.aedReady==='true',null,{timeout:15000});await cue('rescue-arrival');
 await page.locator('[data-cpr-start]').click();await cue('goal-confirm');
 await page.waitForFunction(()=>Number(document.querySelector('[data-cpr-player]')?.dataset.audioRms)>0,{},{timeout:3000});
 await review();
 await page.getByRole('button',{name:'脚边',exact:true}).click();await cue('wrong-warning');
 await page.locator('[data-cpr-position]').click();await cue('goal-confirm');
 await page.getByRole('button',{name:'暂停',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-cpr-player]')?.dataset.audioState==='suspended');
 assert.equal(await root.getAttribute('data-audio-voices'),'0');
 await page.getByRole('button',{name:'关闭声音',exact:true}).click();
 await page.getByRole('button',{name:'继续练习',exact:true}).click();
 await review();
 const mutedCount=await played();await page.locator('[data-cpr-hands]').click();await page.waitForTimeout(400);assert.equal(await played(),mutedCount);
 assert.equal(await root.getAttribute('data-ui-audio-muted'),'true');
 await page.getByRole('button',{name:'暂停',exact:true}).click();await page.getByRole('button',{name:'开启声音',exact:true}).click();await page.getByRole('button',{name:'继续练习',exact:true}).click();await page.waitForTimeout(250);assert.equal(await played(),mutedCount);
 await review();
 await page.locator('[data-cpr-posture]').focus();await page.keyboard.press('Enter');await cue('goal-confirm');
 pass('Pointer/keyboard inputs have shared correct/error cues; pause and mute cancel voices, unmute does not replay');
 await review();
 await page.locator('[data-cpr-tap]').click();await cue('soft-tap');
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
 await page.waitForFunction(()=>document.querySelector('[data-cpr-player]')?.dataset.audioState==='suspended');assert.equal(await root.getAttribute('data-audio-voices'),'0');
 await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
 await page.getByRole('button',{name:'继续练习',exact:true}).click();
 assert.equal(await page.locator('[data-cpr-handover]').count(),0);
 for(let i=0;i<15&&await page.locator('[data-cpr-tap]').count();i++){await page.locator('[data-cpr-tap]').click();await page.waitForTimeout(550);}
 await review();await page.locator('[data-cpr-handover]').click();await cue('goal-confirm');await review();
 await page.locator('[data-cpr-finish]').click();await cue('victory');await page.getByTestId('settlement-title').waitFor();
 pass('Simulated hidden page is silent; AED arrival, rhythm taps and exact approved victory sound work');
 await page.screenshot({path:path.join(out,'cpr-audio-complete.png')});
 await page.getByTestId('settlement-primary').click();await page.locator('[data-journey-map]').waitFor();
 assert.equal(await root.count(),0);assert(await page.evaluate(()=>window.__testAudio.some(c=>c.state==='closed')));
 await enter('first-aid-aed');const aed=page.locator('[data-level="first-aid-aed"]');
 await page.waitForFunction(()=>{const d=document.querySelector('[data-level="first-aid-aed"]')?.dataset;return d?.audioState==='running'&&Number(d.audioLoops)>0;});
 await page.waitForFunction(()=>Number(document.querySelector('[data-level="first-aid-aed"]')?.dataset.audioRms)>0);
 pass('AED retains its existing shared audio engine and produces nonzero Web Audio output');
 await page.screenshot({path:path.join(out,'aed-audio-active.png')});
 assert.deepEqual(report.errors,[]);assert.deepEqual(report.network,[]);report.status='passed';
} catch(error){report.status='failed';report.failure=error.stack;await page?.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});console.error(error);process.exitCode=1;}
finally{await context?.close();await browser?.close();report.closed=true;fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));}
