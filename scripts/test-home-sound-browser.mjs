/** Real exported HTML; isolated profiles, muted browser output, audio-state diagnostics. */
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { root } from './lib/dependencies.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH ?? 'playwright');
const html = path.resolve(root, process.argv[2] ?? 'outputs/本地离线版/小红花应急行动.html');
const out = path.join(root, 'outputs/home-sound-verification');
fs.mkdirSync(out, { recursive: true });
const report = { html, sha256: createHash('sha256').update(fs.readFileSync(html)).digest('hex'), checks: [], errors: [], network: [], browserClosed: false, physicalDevice: 'not_run', humanListening: 'not_run' };
let browser;
const check = name => { report.checks.push(name); console.log('PASS ' + name); };
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.EDGE_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', args: ['--mute-audio'] });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce', hasTouch: true, isMobile: true });
  await context.route(/^https?:/, route => { report.network.push(route.request().url()); return route.abort(); });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  page.on('pageerror', e => report.errors.push(e.message));
  const load = async () => { await page.goto(pathToFileURL(html).href, { waitUntil: 'load', timeout: 120000 }); await page.locator('[data-home-sound]').waitFor(); };
  const trigger = page.locator('[data-home-sound]');
  const panel = page.locator('[data-home-sound-panel]');
  const music = page.locator('[data-home-music-toggle]');
  const effects = page.locator('[data-home-effects-toggle]');
  const audioState = async (muted, playing) => page.waitForFunction(({ muted, playing }) => {
    const d = document.querySelector('.game-page')?.dataset;
    return d?.journeyMusicMuted === String(muted) && d?.journeyMusicPlaying === String(playing);
  }, { muted, playing });
  const storage = key => page.evaluate(key => localStorage.getItem(key), key);
  const uiCount = () => page.locator('.game-page').evaluate(el => Number(el.dataset.uiAudioPlayed ?? 0));
  await load();
  for (const [width, height] of [[390, 844], [320, 568], [1280, 900]]) {
    await page.setViewportSize({ width, height });
    const stage = await page.locator('[data-title-screen]').boundingBox();
    const button = await trigger.boundingBox();
    assert(button.width >= 44 && button.height >= 44);
    assert(button.x >= stage.x + stage.width * .65 && button.y >= stage.y && button.y + button.height <= stage.y + 82);
    await page.screenshot({ path: path.join(out, `home-${width}x${height}.png`) });
    await trigger.click();
    await panel.waitFor();
    const box = await panel.boundingBox();
    assert(box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= height);
    assert(box.x >= stage.x && box.x + box.width <= stage.x + stage.width);
    for (const b of await panel.locator('button').all()) assert((await b.boundingBox()).height >= 44);
    await page.screenshot({ path: path.join(out, `panel-${width}x${height}.png`) });
    await page.keyboard.press('Escape');
    await panel.waitFor({ state: 'detached' });
    assert(await trigger.evaluate(el => el === document.activeElement));
    check(`right-corner control and panel fit ${width}x${height}; Escape restores focus`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await trigger.press('Enter');
  await panel.waitFor();
  assert(await music.evaluate(el => el === document.activeElement));
  await audioState(false, true);
  const before = await uiCount();
  await music.click();
  await audioState(true, false);
  assert.equal(await storage('red-flower:journey-music-muted'), 'true');
  assert.equal(await effects.getAttribute('aria-pressed'), 'true');
  await effects.click();
  assert.equal(await storage('red-flower:interface-muted'), 'true');
  assert.equal(await trigger.getAttribute('data-muted'), 'true');
  assert.equal(await uiCount(), before);
  await panel.getByRole('button', { name: '关闭声音设置' }).click();
  await page.locator('[data-home-unlock-all]').click();
  await page.waitForTimeout(350);
  assert.equal(await uiCount(), before);
  check('both toggles persist separately; music actually stops and muted buttons emit no cues');
  await load();
  assert.equal(await trigger.getAttribute('data-muted'), 'true');
  await trigger.click();
  assert.equal(await music.getAttribute('aria-pressed'), 'false');
  assert.equal(await effects.getAttribute('aria-pressed'), 'false');
  await audioState(true, false);
  await effects.click();
  assert.equal(await trigger.getAttribute('data-muted'), 'false');
  await audioState(true, false);
  await music.click();
  await audioState(false, true);
  assert.equal(await storage('red-flower:interface-muted'), 'false');
  assert.equal(await storage('red-flower:journey-music-muted'), 'false');
  check('refresh remembers both controls; enabling effects does not enable music');
  await page.mouse.click(18, 320);
  await panel.waitFor({ state: 'detached' });
  check('outside pointer dismisses the panel');
  const enabledBefore = await uiCount();
  await page.locator('[data-home-continue]').click();
  await page.locator('[data-journey-map]').waitFor();
  await page.waitForFunction(before => Number(document.querySelector('.game-page')?.dataset.uiAudioPlayed) > before, enabledBefore);
  await page.locator('[data-map-settings]').click();
  const settings = page.getByRole('dialog', { name: '游戏设置', exact: true });
  await settings.waitFor();
  await settings.getByRole('button', { name: '关闭首页和地图音乐' }).click();
  await settings.getByRole('button', { name: '关闭按钮和奖励音效' }).click();
  await settings.getByRole('button', { name: '关闭', exact: true }).click();
  await page.locator('[data-map-home]').click();
  assert.equal(await trigger.getAttribute('data-muted'), 'true');
  await trigger.click();
  assert.equal(await music.getAttribute('aria-pressed'), 'false');
  assert.equal(await effects.getAttribute('aria-pressed'), 'false');
  check('unmuted UI plays feedback and map settings stay synchronized with home');
  await effects.focus();
  await page.keyboard.press('Tab');
  await panel.waitFor({ state: 'detached' });
  check('keyboard can leave the nonmodal panel without a focus trap');
  assert.deepEqual(report.errors, []);
  assert.deepEqual(report.network, []);
  report.status = 'passed';
} catch (error) {
  report.status = 'failed';
  report.failure = error.stack;
  throw error;
} finally {
  if (browser) { await browser.close(); report.browserClosed = true; }
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2));
}